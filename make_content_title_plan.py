with SRC.open(encoding="cp932", newline="") as f:
    reader = csv.DictReader(f)
    products = {}
    for row in reader:
        key = row.get("商品管理番号（商品URL）", "").strip()
        if key and key not in products:
            products[key] = {
                "key": key,
                "name": row.get("商品名", "").strip(),
                "catch": row.get("キャッチコピー", "").strip(),
                "genre": row.get("ジャンルID", "").strip(),
                "image": row.get("商品画像パス1", "").strip(),
            }


def find_products(*needles, limit=6):
    found = []
    for p in products.values():
        text = p["name"] + " " + p["catch"]
        if any(n in text for n in needles):
            found.append(p["key"])
        if len(found) >= limit:
            break
    return " / ".join(found)


